DEMO_COMPANY_ID = "portwatch-demo-shipping"


def demo_company(
    *,
    seed: int = 20260909,
    vessel_count: int = 14,
    company_id: str = DEMO_COMPANY_ID,
    name: str = "PortWatch Demo Shipping",
    short_name: str = "PWD",
) -> CompanyProfile:
    """Build the fictional demo carrier. Deterministic given the seed.

    Determinism matters here for the same reason it does in the traffic replay:
    the fleet screen has to show the same thing on every run, or a screenshot is
    not reviewable and a browser test is not stable.
    """
    rng = random.Random(seed)
    vessels: List[FleetVessel] = []

    for index in range(vessel_count):
        klass, loa, beam, draught, teu, plugs, speed = rng.choice(_CLASSES)
        lane_code, origin, destination, onward = _ROTATIONS[index % len(_ROTATIONS)]
        lane = TRADE_LANES.get(lane_code)

        # Hours to each chokepoint on the routing. Spread across the passage so
        # some vessels are still short of the strait, some are inside it and some
        # are through -- which is the whole point of the exposure timing gate.
        hours: Dict[str, float] = {}
        for position, chokepoint in enumerate(lane.chokepoints if lane else ()):
            # Negative means already past. A third of the fleet is, by design.
            base = rng.uniform(-40.0, 96.0)
            hours[chokepoint] = round(base + position * rng.uniform(20.0, 60.0), 1)

        loaded = rng.uniform(0.55, 0.94)
        vessels.append(
            FleetVessel(
                vessel_id=f"{short_name}-{index + 1:03d}",
                name=f"MV {_NAMES[index % len(_NAMES)]}",
                imo=None,
                vessel_class=klass,
                loa_m=loa,
                beam_m=beam,
                draught_m=draught * rng.uniform(0.88, 1.0),
                capacity_teu=teu,
                reefer_plugs=plugs,
                service_speed_kn=speed * rng.uniform(0.92, 1.02),
                flag="IN" if lane_code.startswith("COAST") else rng.choice(["SG", "MT", "PA", "IN"]),
                origin_port=origin,
                destination_port=destination,
                lane_code=lane_code,
                hours_to_chokepoint=hours,
                available_teu=round(teu * (1 - loaded), 0),
                available_reefer_plugs=int(plugs * (1 - loaded)),
                accepts_hazardous=rng.random() < 0.55,
                accepts_oog=rng.random() < 0.8,
                onward_ports=list(onward),
                position_source=SOURCE_SIMULATED,
                cargo_value_index=round(rng.uniform(0.3, 0.95), 2),
            )
        )

    return CompanyProfile(
        company_id=company_id,
        name=name,
        short_name=short_name,
        verified=False,
        home_ports=["INNSA", "INMAA", "INMUN"],
        vessels=vessels,
        position_source=SOURCE_SIMULATED,
    )


def attach_etas(profile: CompanyProfile, epoch_ms: int) -> CompanyProfile:
    """Give every vessel an ETA anchored to the pipeline's forecast origin.

    Anchoring to the pipeline clock rather than the wall clock keeps the fleet
    screen consistent with the port state it sits next to, and keeps a
    screenshot identical between runs.
    """
    from datetime import datetime, timedelta, timezone

    base = datetime.fromtimestamp(epoch_ms / 1000.0, tz=timezone.utc)
    for index, vessel in enumerate(profile.vessels):
        digest = int(hashlib.sha1(vessel.vessel_id.encode()).hexdigest()[:6], 16)
        hours = 6 + (digest % 96) + index * 0.7
        vessel.eta = (base + timedelta(hours=hours)).isoformat(timespec="seconds")
    return profile


def from_provider(payload: Dict[str, Any]) -> CompanyProfile:
    """Build a company profile from a real provider's payload.

    The seam. A licensed fleet-management or AIS provider maps its own schema
    onto this shape and everything downstream works unchanged -- exposure,
    cargo, advisories and the fleet screens all read :class:`CompanyProfile`.

    ``verified`` comes from the payload rather than being assumed: a provider
    that does not assert it is not treated as verified, and the UI then shows the
    same "demo" framing it does for the fictional carrier.
    """
    vessels = [
        FleetVessel(
            vessel_id=str(row["vesselId"]),
            name=str(row["name"]),
            imo=row.get("imo"),
            vessel_class=str(row.get("vesselClass", "container")),
            loa_m=float(row.get("loaM", 0.0)),
            beam_m=float(row.get("beamM", 0.0)),
            draught_m=float(row.get("draughtM", 0.0)),
            capacity_teu=int(row.get("capacityTeu", 0)),
            reefer_plugs=int(row.get("reeferPlugs", 0)),
            service_speed_kn=float(row.get("serviceSpeedKn", 16.0)),
            flag=str(row.get("flag", "")),
            origin_port=row.get("originPort"),
            destination_port=row.get("destinationPort"),
            lane_code=row.get("laneCode"),
            eta=row.get("eta"),
            hours_to_chokepoint={
                str(k): float(v) for k, v in (row.get("hoursToChokepoint") or {}).items()
            },
            available_teu=float(row.get("availableTeu", 0.0)),
            available_reefer_plugs=int(row.get("availableReeferPlugs", 0)),
            accepts_hazardous=bool(row.get("acceptsHazardous", False)),
            accepts_oog=bool(row.get("acceptsOog", False)),
            onward_ports=list(row.get("onwardPorts") or []),
            position_source=str(row.get("positionSource", SOURCE_PROVIDER)),
            lat=row.get("lat"),
            lon=row.get("lon"),
        )
        for row in (payload.get("vessels") or [])
    ]
    verified = bool(payload.get("verified", False))
    return CompanyProfile(
        company_id=str(payload["companyId"]),
        name=str(payload["name"]),
        short_name=str(payload.get("shortName", payload["name"][:3].upper())),
        verified=verified,
        home_ports=list(payload.get("homePorts") or []),
        vessels=vessels,
        position_source=str(payload.get("positionSource", SOURCE_PROVIDER)),
        disclaimer=(
            "" if verified else
            "Unverified carrier account. Positions and voyages come from the "
            "configured provider and have not been confirmed against a licensed "
            "AIS feed."
        ),
    )


def capacities_for(
    profile: CompanyProfile,
    *,
    port_code: Optional[str] = None,
    now_hour: float = 0.0,
) -> List[Any]:
    """Fleet vessels expressed as cargo capacity, for the transshipment layer."""
    from src.portwatch_os.cargo.model import VesselCapacity

    out: List[VesselCapacity] = []
    for index, vessel in enumerate(profile.vessels):
        if port_code and vessel.destination_port != port_code:
            continue
        # Sailing times are spread across the next three days so the connection
        # window is a live constraint rather than a formality. The first sailing
        # is far enough out that inbound cargo has time to make it -- otherwise
        # the earliest vessels are unusable and the window stops being the thing
        # under test.
        departure = now_hour + 18.0 + (index * 7.0) % 78.0
        out.append(
            VesselCapacity(
                vessel_id=vessel.vessel_id,
                name=vessel.name,
                available_teu=vessel.available_teu,
                available_reefer_plugs=vessel.available_reefer_plugs,
                accepts_hazardous=vessel.accepts_hazardous,
                accepts_oog=vessel.accepts_oog,
                onward_ports=list(vessel.onward_ports),
                departure_hour=departure,
                load_cutoff_hour=departure - 3.0,
                operator=profile.name,
            )
        )
    return out


