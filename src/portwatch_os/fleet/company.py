"""The demo shipping company.

**This carrier does not exist, and its voyages are not real.** No Maersk, MSC or
CMA CGM vessel appears anywhere in this product, and no real vessel's voyage is
represented. The fleet below belongs to a fictional operator so the Shipping
Company workspace has something coherent to reason about, and every surface that
shows it carries :data:`COMPANY_DISCLAIMER`.

What is architecturally real is the seam. :class:`CompanyProfile` and
:class:`FleetVessel` are what a real carrier account would populate, and
:func:`from_provider` is where a licensed AIS or fleet-management feed plugs in.
Every downstream consumer -- Global Eye exposure, cargo, advisories -- reads this
interface and not the demo data, so replacing the demo carrier with a real one is
a provider implementation and nothing else.

Vessel names are Indian Ocean geography, deliberately unlike any operating
carrier's naming convention, so a screenshot cannot be mistaken for a real fleet.
"""

from __future__ import annotations

import hashlib
import random
from dataclasses import asdict, dataclass, field
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

from src.portwatch_os.global_eye.exposure import TRADE_LANES, VesselVoyage
from src.utils import port_registry, provenance

COMPANY_DISCLAIMER = (
    "Demo carrier. PortWatch Demo Shipping is a fictional operator created so "
    "the fleet workspace has a coherent subject. Its vessels, voyages, cargo and "
    "schedules are generated by this application and are not, and do not "
    "represent, any real carrier, vessel or commercial voyage. The company "
    "account interface is the seam a licensed fleet or AIS provider plugs into."
)

#: Where positions come from. Taken from the provenance vocabulary rather than
#: written out here, so a company fleet, the national picture and the pipeline's
#: own registry cannot drift into describing the same thing three ways.
SOURCE_SIMULATED = provenance.SIMULATED_TRAFFIC
SOURCE_LIVE_AIS = "LIVE_AIS"
SOURCE_PROVIDER = "FLEET_PROVIDER"


@dataclass
class FleetVessel:
    """One vessel in a company fleet, and the voyage it is running."""

    vessel_id: str
    name: str
    #: Always ``None`` for the demo fleet: no IMO number was issued to a
    #: fictional hull, and inventing one would make it look registrable.
    imo: Optional[str]
    vessel_class: str
    loa_m: float
    beam_m: float
    draught_m: float
    capacity_teu: int
    reefer_plugs: int
    service_speed_kn: float
    flag: str

    #: Current voyage.
    origin_port: Optional[str] = None
    destination_port: Optional[str] = None
    lane_code: Optional[str] = None
    eta: Optional[str] = None
    #: Hours to each chokepoint on the current routing. The timing that decides
    #: whether a diversion is still available.
    hours_to_chokepoint: Dict[str, float] = field(default_factory=dict)
    #: Slots still free, for the cargo layer.
    available_teu: float = 0.0
    available_reefer_plugs: int = 0
    accepts_hazardous: bool = False
    accepts_oog: bool = True
    #: Onward rotation after the current call.
    onward_ports: List[str] = field(default_factory=list)
    #: Where the position came from. Never inferred.
    position_source: str = SOURCE_SIMULATED
    lat: Optional[float] = None
    lon: Optional[float] = None
    cargo_value_index: float = 0.5

    def to_voyage(self) -> VesselVoyage:
        """The shape the Global Eye exposure graph consumes."""
        return VesselVoyage(
            vessel_id=self.vessel_id,
            name=self.name,
            lane_code=self.lane_code,
            destination_port=self.destination_port,
            hours_to_chokepoint=dict(self.hours_to_chokepoint),
            eta=self.eta,
            service_speed_kn=self.service_speed_kn,
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            **asdict(self),
            "laneName": (
                TRADE_LANES[self.lane_code].name if self.lane_code in TRADE_LANES else None
            ),
        }


@dataclass
class CompanyProfile:
    """A carrier account. The seam a real operator plugs into."""

    company_id: str
    name: str
    short_name: str
    #: True only for a real, contracted carrier account. Always False here.
    verified: bool
    home_ports: List[str] = field(default_factory=list)
    vessels: List[FleetVessel] = field(default_factory=list)
    #: What the fleet positions actually are.
    position_source: str = SOURCE_SIMULATED
    disclaimer: str = COMPANY_DISCLAIMER

    def vessel(self, vessel_id: str) -> Optional[FleetVessel]:
        return next((v for v in self.vessels if v.vessel_id == vessel_id), None)

    def voyages(self) -> List[VesselVoyage]:
        return [v.to_voyage() for v in self.vessels]

    def vessel_ids(self) -> List[str]:
        return [v.vessel_id for v in self.vessels]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "companyId": self.company_id,
            "name": self.name,
            "shortName": self.short_name,
            "verified": self.verified,
            "homePorts": self.home_ports,
            "vesselCount": len(self.vessels),
            "vessels": [v.to_dict() for v in self.vessels],
            "positionSource": self.position_source,
            "disclaimer": self.disclaimer,
        }


