/** Static particulars — everything that does not change between fixes. */
export interface Vessel {
  id: string;
  /** Callable identity in the replay. Never an IMO number: none was issued. */
  replayId: string;
  imo: string | null;
  name: string;
  operator: string;
  callsign: string;
  flag: string;
  vesselClass: VesselClass;
  lengthM: number;
  beamM: number;
  draughtM: number;
  dwt: number;
  /** Waypoint ids for the current voyage. */
  originId: string;
  destinationId: string;
  /** Waypoint id of the Indian port this vessel is operationally attached to. */
  homePortId: string | null;
  serviceSpeedKn: number;
  /** True for a vessel the signed-in operator owns. */
  owned: boolean;
}

/** A vessel resolved to an instant. */
export interface VesselFix extends Vessel {
  at: number;
  lon: number;
  lat: number;
  /** Course over ground, degrees true. */
  cog: number;
  /** Heading, degrees true. Equal to COG under way; it is a replay. */
  heading: number;
  sogKn: number;
  status: NavStatus;
  /** 0 at the origin quay, 1 at the destination quay. */
  progress: number;
  travelledKm: number;
  remainingKm: number;
  /**
   * The vessel's next scheduled event, epoch ms. What that event is depends on
   * where the vessel is, and `etaKind` says which -- a port controller reading
   * a row needs to know whether 14:20 is an arrival off the fairway buoy or the
   * moment a berth frees up.
   */
  etaMs: number | null;
  etaMinutes: number | null;
  etaKind: "arrival" | "berthing" | "departure" | null;
  /** The passage this vessel is running, oriented origin to destination. */
  routeKey: string | null;
}

/* ---------------------------------------------------------------- source -- */

export interface TrafficSource {
  readonly info: TrafficSourceInfo;
  /** Static particulars for the whole fleet. */
  roster(): Vessel[];
  /** Every vessel resolved to `at`, in epoch milliseconds. */
  fixes(at: number): VesselFix[];
  /** One vessel resolved to `at`, or null if the id is unknown. */
  fix(id: string, at: number): VesselFix | null;
  /** The passage geometry for a vessel, or null where none applies. */
  route(id: string): { coords: Position[]; km: number } | null;
}
