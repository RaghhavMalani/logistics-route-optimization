/**
 * The traffic contract.
 *
 * One shape for a vessel on the map, and one enumeration for where it came
 * from. Every screen consumes `VesselFix` and asks the source what it is; no
 * screen knows whether the positions behind it were received over a live AIS
 * link or produced by the replay engine. Swapping a real provider in later is a
 * new implementation of `TrafficSource` and nothing else.
 */

import type { Position } from "./geo";

/* ---------------------------------------------------------------- source -- */

/**
 * Where positions come from. This is the honesty seam of the whole traffic
 * layer, and it is never inferred: a source declares its own kind.
 *
 *   LIVE_AIS            a terrestrial or satellite AIS provider, streaming.
 *   AIS_REPLAY          recorded AIS positions, replayed against a clock.
 *   SIMULATED_TRAFFIC   positions generated by this application. Not observed.
 *   UNAVAILABLE         no provider is configured or reachable.
 */
export type TrafficSourceKind =
  | "LIVE_AIS"
  | "AIS_REPLAY"
  | "SIMULATED_TRAFFIC"
  | "UNAVAILABLE";

export interface TrafficSourceInfo {
  kind: TrafficSourceKind;
  /** Two or three words for the status strip. */
  label: string;
  provider: string;
  /** One sentence a reader can act on: what this is, and what it is not. */
  detail: string;
  /** Wall-clock instant the replay clock is anchored to. */
  epoch: number;
  /** True only when positions were actually observed by a receiver. */
  observed: boolean;
}

